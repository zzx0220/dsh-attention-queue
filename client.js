    /**
     * Fold the live feeds into the queue. Runs on every sessions/status change:
     *
     *  - running: true        -> the session is working; drop any entry
     *  - waiting on you       -> needs reply (never for the session on screen)
     *  - running true -> false while elsewhere -> unseen
     *  - the session came on screen unseen -> mark it viewed
     *
     * @param list - the `useSessions` snapshot.
     * @param statuses - the `useSessionStatus` map.
     * @param currentId - the session the main view shows, if any.
     */
    function reconcile(list, statuses, currentId) {
      if (list === undefined || list === null || list.byId === undefined) return;
      var ids = list.ids || Object.keys(list.byId);
      var now = Date.now();
      var dirty = false;
      var present = new Set(ids);

      for (const id of ids) {
        var session = list.byId[id];
        if (session === undefined) continue;
        // Subagent children and untouched drafts are not conversations to triage.
        if (session.blank === true || session.origin === 'subagent') {
          delete lastRunning[id];
          continue;
        }

        var status = statusOf(statuses, id);
        var running = status?.running !== undefined ? status.running === true : session.running === true;
        var pendingKind = status?.pendingInteraction?.kind;
        var entry = store.entries[id];
        var wasRunning = lastRunning[id] === true;

        if (running) {
          lastRunning[id] = true;
          if (entry !== undefined) {
            delete store.entries[id];
            dirty = true;
          }
          continue;
        }

        lastRunning[id] = false;

        var isCurrent = id === currentId;

        // Viewed, then left: settle it now. Staying on a row while you read it is
        // the whole point — the entry must survive the visit and only resolve
        // once you have moved on to another conversation.
        if (entry !== undefined && entry.viewedAt !== undefined && !isCurrent) {
          if (pendingKind !== undefined) {
            store.entries[id] = Object.assign({}, entry, { state: 'reply', reason: pendingKind });
          } else {
            delete store.entries[id];
          }
          dirty = true;
          continue;
        }

        if (pendingKind !== undefined && !isCurrent) {
          if (entry === undefined || entry.state !== 'reply') {
            store.entries[id] = makeEntry(session, 'reply', pendingKind, now);
            dirty = true;
            announce(session, 'reply');
          }
          continue;
        }

        if (isCurrent) {
          // Seen: remember the visit instead of dropping the row.
          if (entry !== undefined && entry.viewedAt === undefined) {
            store.entries[id] = Object.assign({}, entry, { viewedAt: now });
            dirty = true;
          }
          continue;
        }

        if (wasRunning === true && entry === undefined) {
          store.entries[id] = makeEntry(session, 'unseen', 'finished', now);
          dirty = true;
          announce(session, 'unseen');
        }
      }

      // Sessions that vanished (archived/deleted) leave the queue too.
      for (const id of Object.keys(store.entries)) {
        if (!present.has(id)) {
          delete store.entries[id];
          dirty = true;
        }
      }

      // First ready snapshot after a page load: recover what finished while the
      // page was closed (the shipped completion set is memory-only).
      if (restorePending && list.phase === 'ready') {
        restorePending = false;
        for (const id of ids) {
          var rested = list.byId[id];
          if (rested === undefined || rested.blank === true) continue;
          if (rested.origin === 'subagent' || id === currentId) continue;
          if ((Number(rested.updatedAt) || 0) <= store.lastExit) continue;
          if (store.entries[id] !== undefined) continue;
          var dismissedAt = Number(store.dismissed[id]) || 0;
          if (dismissedAt >= (Number(rested.updatedAt) || 0)) continue;
          store.entries[id] = makeEntry(rested, 'unseen', 'restored', now);
          dirty = true;
        }
      }

      if (dirty) emit();
    }

