      var ids = Object.keys(store.dismissed);
      if (ids.length <= 200) return;
      ids.sort((a, b) => (Number(store.dismissed[a]) || 0) - (Number(store.dismissed[b]) || 0));
      for (var index = 0; index < ids.length - 200; index += 1) delete store.dismissed[ids[index]];
