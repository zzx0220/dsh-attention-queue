    /** Service handles the pure helpers above need (assigned in apply). */
    var injectRefs = { uiWorkspace: undefined };

    /** Probe the navigation face: `ctx.get` first (absent services throw), then the property. */
    function resolveUiWorkspace(ctx) {
      try {
        var viaGet = typeof ctx.get === 'function' ? ctx.get('uiWorkspace') : undefined;
        if (viaGet !== undefined && viaGet !== null) return viaGet;
      } catch (error) {
        /* not mounted in this app */
      }
      try {
        return ctx.uiWorkspace;
      } catch (error) {
        return undefined;
      }
    }

    /**
     * Mount the queue card into the frame overlay whenever that slot exists.
     * @param ctx - browser services of this plugin.
     */
    function apply(ctx) {
      injectRefs.uiWorkspace = resolveUiWorkspace(ctx);
      try {
        if (typeof Notification !== 'undefined' && Notification.permission === 'default') {
          Notification.requestPermission();
        }
      } catch (error) {
        /* the desktop shell grants it by itself */
      }
      ctx.slots.inject('shell.overlay', () =>
        ctx.slots.register(
          { name: 'shell.overlay', id: 'attention-queue', order: 90000 },
          AttentionQueue,
        ),
      );
    }

    exports.inject = inject;
    exports.apply = apply;
    /**
     * Test seam: the pure state machine is driven from Node with stubbed feeds,
     * so the transition table can be exercised without a browser.
     */
    exports.__internals = { reconcile: reconcile, store: store, reset: resetForTests, copy: copy, languages: COPY };

    /** Forget every entry and baseline (test seam only). */
    function resetForTests() {
      store.entries = {};
      store.dismissed = {};
      store.lastExit = 0;
      restorePending = true;
      for (const id of Object.keys(lastRunning)) delete lastRunning[id];
      version += 1;
    }

    return module.exports;
