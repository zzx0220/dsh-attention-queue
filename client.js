      var rootRef = React.useRef(null);
      var anchor = useAnchor(rootRef);
      useHostLanguage();
      var list = typeof props.useSessions === 'function' ? props.useSessions(identity) : undefined;
      var statuses = typeof props.useSessionStatus === 'function' ? props.useSessionStatus(identity) : undefined;
      var currentId = currentSessionId(list);

      // Re-render whenever the queue changes.
      React.useSyncExternalStore(subscribe, getVersion, getVersion);

