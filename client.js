    /** Dismissal marks the current activity, so a restart will not resurrect it. */
    function dismiss(id) {
      var entry = store.entries[id];
      if (entry === undefined) return;
      store.dismissed[id] = entry.activeAt;
      delete store.entries[id];
      emit();
    }

    function markReply(id) {
      var entry = store.entries[id];
      if (entry === undefined) return;
      store.entries[id] = Object.assign({}, entry, { state: 'reply', reason: 'manual' });
      emit();
    }

    function clearAll() {
      for (const id of Object.keys(store.entries)) {
        var entry = store.entries[id];
        store.dismissed[id] = entry.activeAt;
      }
      store.entries = {};
      emit();
    }

