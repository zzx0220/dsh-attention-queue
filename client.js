/**
 * attention-queue, browser half.
 *
 * A hand-written ModuleLoader bundle (no build step). It answers one question
 * the shipped sidebar does not: which sessions are *waiting on me*, across
 * every workspace, and did I already look at them?
 *
 * The shipped UI already knows two of the three facts:
 *
 *   - `useSessionStatus` publishes, per session, `running`,
 *     `pendingInteraction.kind` ('approval' | 'plan-review' | 'question') and
 *     `completionUnread` (set when a run goes true -> false and cleared when it
 *     runs again).
 *   - `useSessions` publishes the list (`displayTitle`, `cwd`, `updatedAt`,
 *     `blank`, `origin`, `retainedBy`).
 *
 * What it does not do is *accumulate* them: `completionUnread` is an in-memory
 * Set of the page, so a reload forgets everything, and the facts are scattered
 * across workspace groups as small dots. This bundle owns a persistent queue
 * instead, and renders it as one pinned card over the sidebar:
 *
 *   Unseen      — finished while you were elsewhere and never opened (green)
 *   Needs reply — you looked, and it still wants an answer: an approval, a
 *                 plan review, a question, or anything you mark by hand (amber)
 *
 * Viewing an entry resolves it: "still pending" becomes needs-reply, and
 * everything else is dropped (the "seen it, nothing to do" case). Sending the
 * session a new
 * message, or dismissing a row, clears it too.
 *
 * Placement: `shell.overlay` is the one list-kind, root-scope slot above the
 * sidebar (the sidebar's own browsing region is a single-occupant slot, so
 * occupying it would shadow the shipped browser). The card anchors itself to
 * the measured bounding box of the browser region and falls back to the frame
 * corner when that element cannot be found.
 *
 * Generated by an AI agent (DeepSeek Harness, deepseek-flash).
 */
